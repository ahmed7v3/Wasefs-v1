import { LOCALES } from "@wasfa/shared/i18n";
import {
  ACCOUNT_TYPES,
  COUNTRY_CODE_PATTERN,
  E164_PATTERN,
  PROFESSIONS,
  USER_STATUSES,
} from "@wasfa/shared/identity";
import { sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

import { citext, idColumn, inList, matches, timestamps } from "./columns.js";

/*
 * The account itself. Better Auth owns the first block of columns (names and types are what its
 * Drizzle adapter expects, checked with `@better-auth/cli generate` against v1.7.7); the second
 * block is ours. Ids are generated by Postgres (`advanced.database.generateId: false` in Task 1.3).
 *
 * A user is never hard-deleted: deletion sets `status = 'deleted'`, then a worker job anonymizes
 * the row after 14 days (email replaced, phone and profile wiped), which keeps foreign keys from
 * payments and audit history valid.
 */
export const users = pgTable(
  "users",
  {
    id: idColumn(),

    // --- Better Auth core ---
    name: text().notNull(),
    email: citext().notNull().unique(),
    emailVerified: boolean().notNull().default(false),
    image: text(),
    // two-factor plugin
    twoFactorEnabled: boolean().notNull().default(false),
    // phone-number plugin: mapped to `phoneNumber` / `phoneNumberVerified` in the auth config.
    // Verification is ours (inbound WhatsApp, Task 1.5): `phone_verified` mirrors
    // `phone_verified_at` (CHECK below), so the plugin's boolean can never disagree with it.
    phone: text(),
    phoneVerified: boolean().notNull().default(false),

    // --- Wasfa ---
    phoneVerifiedAt: timestamp({ withTimezone: true }),
    accountType: text({ enum: ACCOUNT_TYPES }).notNull().default("individual"),
    locale: text({ enum: LOCALES }).notNull().default("ar"),
    status: text({ enum: USER_STATUSES }).notNull().default("active"),
    suspendedReason: text(),
    // Set together with `status = 'deleted'` (the deletion request); the account is unusable from then on.
    deletedAt: timestamp({ withTimezone: true }),
    // Set by the worker once personal data has been wiped (14 days after the request).
    anonymizedAt: timestamp({ withTimezone: true }),
    lastLoginAt: timestamp({ withTimezone: true }),
    ...timestamps(),
  },
  (table) => [
    check("users_account_type_check", inList(table.accountType, ACCOUNT_TYPES)),
    check("users_locale_check", inList(table.locale, LOCALES)),
    check("users_status_check", inList(table.status, USER_STATUSES)),
    check(
      "users_phone_format_check",
      sql`${table.phone} is null or ${matches(table.phone, E164_PATTERN.source)}`,
    ),
    check(
      "users_phone_verified_sync_check",
      sql`${table.phoneVerified} = (${table.phoneVerifiedAt} is not null)`,
    ),
    check(
      "users_phone_verified_needs_phone_check",
      sql`${table.phoneVerifiedAt} is null or ${table.phone} is not null`,
    ),
    check(
      "users_deleted_sync_check",
      sql`(${table.status} = 'deleted') = (${table.deletedAt} is not null)`,
    ),
    check(
      "users_anonymized_needs_deleted_check",
      sql`${table.anonymizedAt} is null or ${table.status} = 'deleted'`,
    ),
    // One verified account per phone number (anti-farming of the free tier). Unverified claims may
    // repeat: anyone can type any number, only the WhatsApp proof makes it theirs.
    uniqueIndex("users_phone_verified_key")
      .on(table.phone)
      .where(sql`${table.phoneVerifiedAt} is not null`),
    // Sign-in by phone looks the number up before knowing whether it is verified.
    index("users_phone_idx")
      .on(table.phone)
      .where(sql`${table.phone} is not null`),
    // The worker's "who is due for anonymization" query.
    index("users_pending_anonymization_idx")
      .on(table.deletedAt)
      .where(sql`${table.deletedAt} is not null and ${table.anonymizedAt} is null`),
  ],
);

/** Who the user is professionally. One row per user, created lazily; every field is optional until onboarding fills it. */
export const userProfiles = pgTable(
  "user_profiles",
  {
    userId: uuid()
      .primaryKey()
      .references(() => users.id, { onDelete: "cascade" }),
    // Shown in the UI; falls back to `users.name` when empty.
    displayName: text(),
    profession: text({ enum: PROFESSIONS }),
    // Free-form tags chosen in onboarding (validated against a catalog by the api, Task 1.7).
    usageIntent: text().array().notNull().default([]),
    country: text(),
    city: text(),
    ...timestamps(),
  },
  (table) => [
    check(
      "user_profiles_profession_check",
      sql`${table.profession} is null or ${inList(table.profession, PROFESSIONS)}`,
    ),
    check(
      "user_profiles_country_check",
      sql`${table.country} is null or ${matches(table.country, COUNTRY_CODE_PATTERN.source)}`,
    ),
  ],
);

export type User = typeof users.$inferSelect;
export type NewUser = typeof users.$inferInsert;
export type UserProfile = typeof userProfiles.$inferSelect;
export type NewUserProfile = typeof userProfiles.$inferInsert;
