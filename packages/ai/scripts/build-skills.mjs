#!/usr/bin/env node
/*
 * Builds `src/skills/registry.generated.ts` from `/skills/<name>/SKILL.md`. The skills are the
 * versioned prompts of the AI features; the registry is committed so the API and the worker import
 * plain TypeScript (no file reads at run time). The skill version is `<name>@<hash>`, where the
 * hash is the first 12 hex characters of the SHA-256 of the file with LF line endings (so Windows
 * checkouts hash like Linux). Any edit to a SKILL.md changes the version, which is part of the
 * exact-match cache key.
 *
 *   node scripts/build-skills.mjs          write the file
 *   node scripts/build-skills.mjs --check  exit 1 when the committed file is stale (CI and tests)
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SKILLS_DIR = resolve(here, "../../../skills");
export const OUTPUT = resolve(here, "../src/skills/registry.generated.ts");

const TASKS = [
  "rx_extract",
  "rx_verify",
  "chat",
  "deep_think",
  "web_search",
  "title_gen",
  "classify",
  "summarize",
];

/** `key: value` lines of the frontmatter; `[a, b]` is a list. Anything fancier is a build error. */
function parseFrontmatter(raw, file) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  if (!match) throw new Error(`${file}: missing frontmatter`);
  const fields = {};
  for (const line of match[1].split("\n")) {
    if (line.trim() === "") continue;
    const pair = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error(`${file}: cannot read frontmatter line "${line}"`);
    const value = pair[2].trim();
    fields[pair[1]] = value.startsWith("[")
      ? value
          .slice(1, -1)
          .split(",")
          .map((item) => item.trim())
          .filter(Boolean)
      : value;
  }
  return { fields, body: match[2].trim() };
}

export function readSkills(dir = SKILLS_DIR) {
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  return names.map((name) => {
    const file = join(dir, name, "SKILL.md");
    const raw = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    const { fields, body } = parseFrontmatter(raw, file);
    if (fields.name !== name) throw new Error(`${file}: name must equal the folder name`);
    if (typeof fields.description !== "string" || fields.description === "") {
      throw new Error(`${file}: description is required`);
    }
    if (!Array.isArray(fields.tasks) || fields.tasks.length === 0) {
      throw new Error(`${file}: tasks is required`);
    }
    for (const task of fields.tasks) {
      if (!TASKS.includes(task)) throw new Error(`${file}: unknown task "${task}"`);
    }
    return {
      name,
      description: fields.description,
      tasks: fields.tasks,
      body,
      hash: createHash("sha256").update(raw).digest("hex").slice(0, 12),
    };
  });
}

export function render(skills) {
  const entries = skills
    .map(
      (skill) => `  {
    name: ${JSON.stringify(skill.name)},
    description: ${JSON.stringify(skill.description)},
    tasks: ${JSON.stringify(skill.tasks)},
    body: ${JSON.stringify(skill.body)},
    hash: ${JSON.stringify(skill.hash)},
  },`,
    )
    .join("\n");
  return `/*
 * GENERATED by packages/ai/scripts/build-skills.mjs from /skills/<name>/SKILL.md. Do not edit:
 * run \`pnpm --filter @wasfa/ai build:skills\`. A test fails when this file is stale.
 */
import type { SkillEntry } from "./types.js";

// prettier-ignore
export const SKILL_REGISTRY: readonly SkillEntry[] = [
${entries}
];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = render(readSkills());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // A missing file is stale too.
    }
    if (current !== next) {
      process.stderr.write("registry.generated.ts is stale: run `pnpm --filter @wasfa/ai build:skills`\n");
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, next);
  }
}
