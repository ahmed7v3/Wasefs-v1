import type { ContentType, ContentLocale } from "@wasfa/shared/content/constants";
import type {
  ContentItemDetail,
  ContentMeta,
  ContentMetaPatch,
  ContentPayload,
  ContentPayloadPatch,
  CreateContentItemInput,
  UpdateContentItemInput,
} from "@wasfa/shared/schemas/content";

/*
 * What the editor holds while you type, and how it turns into API bodies. The draft is the WHOLE
 * editable state (reviewed payload + item metadata); the server baseline is the last detail we loaded.
 * Patches contain only the fields that differ: a PATCH for a changed title must not re-send (and so
 * overwrite) a body somebody else just saved.
 */

export interface EditorDraft {
  payload: ContentPayload;
  meta: ContentMeta;
}

export function emptyDraft(): EditorDraft {
  return {
    payload: { title: "", excerpt: "", definition: "", bodyMd: "" },
    meta: {
      slug: "",
      categoryId: null,
      tagIds: [],
      primaryAuthorId: null,
      reviewerId: null,
      featuredMediaId: null,
      seo: {
        title: "",
        description: "",
        canonical: "",
        robots: "index",
        focusKeyword: "",
        secondaryKeywords: [],
        ogTitle: "",
        ogDescription: "",
        ogImageMediaId: null,
      },
      flags: {
        autoLink: true,
        showToc: false,
        showRelated: true,
        sponsored: false,
        aiAssisted: false,
      },
    },
  };
}

export function draftFromDetail(detail: ContentItemDetail): EditorDraft {
  return { payload: { ...detail.payload }, meta: structuredClone(detail.meta) };
}

const same = (a: unknown, b: unknown): boolean => JSON.stringify(a) === JSON.stringify(b);

/** The keys of `draft` whose value differs from `base`. */
function changedKeys<T extends object>(base: T, draft: T): Partial<T> | undefined {
  const out: Partial<T> = {};
  let any = false;
  for (const key of Object.keys(draft) as (keyof T)[]) {
    if (!same(base[key], draft[key])) {
      out[key] = draft[key];
      any = true;
    }
  }
  return any ? out : undefined;
}

export function payloadPatch(
  base: ContentPayload,
  draft: ContentPayload,
): ContentPayloadPatch | undefined {
  return changedKeys(base, draft);
}

export function metaPatch(base: ContentMeta, draft: ContentMeta): ContentMetaPatch | undefined {
  const { seo: baseSeo, flags: baseFlags, ...baseRest } = base;
  const { seo: draftSeo, flags: draftFlags, ...draftRest } = draft;
  const out: Record<string, unknown> = { ...changedKeys(baseRest, draftRest) };
  // An empty slug is "not chosen yet", never a rename to nothing.
  if (draftRest.slug.trim() === "") delete out["slug"];
  const seo = changedKeys(baseSeo, draftSeo);
  const flags = changedKeys(baseFlags, draftFlags);
  if (seo) out["seo"] = seo;
  if (flags) out["flags"] = flags;
  // The keys come from `ContentMeta`, so the patch has exactly the shape of `ContentMetaPatch`.
  return Object.keys(out).length > 0 ? (out as ContentMetaPatch) : undefined;
}

export const isPayloadDirty = (base: ContentPayload, draft: ContentPayload): boolean =>
  payloadPatch(base, draft) !== undefined;

export const isMetaDirty = (base: ContentMeta, draft: ContentMeta): boolean =>
  metaPatch(base, draft) !== undefined;

/** A stable string of the payload: the autosave scheduler compares these to skip unchanged saves. */
export const serializePayload = (payload: ContentPayload): string =>
  JSON.stringify([payload.title, payload.excerpt, payload.definition, payload.bodyMd]);

/** `PATCH /admin/content/items/:id`, or null when nothing differs. */
export function buildUpdateBody(
  base: EditorDraft,
  draft: EditorDraft,
  lockVersion: number,
  note?: string,
): UpdateContentItemInput | null {
  const payload = payloadPatch(base.payload, draft.payload);
  const meta = metaPatch(base.meta, draft.meta);
  if (!payload && !meta) return null;
  return {
    lockVersion,
    ...(payload ? { payload } : {}),
    ...(meta ? { meta } : {}),
    ...(note && note.trim() !== "" ? { note: note.trim() } : {}),
  };
}

/** `POST /admin/content/items`: the slug is generated by the server when still empty. */
export function buildCreateBody(input: {
  type: ContentType;
  locale: ContentLocale;
  translationOf?: string | undefined;
  draft: EditorDraft;
}): CreateContentItemInput {
  const { slug, ...rest } = input.draft.meta;
  return {
    type: input.type,
    locale: input.locale,
    ...(input.translationOf ? { translationOf: input.translationOf } : {}),
    payload: input.draft.payload,
    meta: slug.trim() === "" ? rest : { slug: slug.trim(), ...rest },
  };
}

/** Draft for the English (or Arabic) twin: the title and metadata that make sense across languages. */
export function twinDraft(from: EditorDraft): EditorDraft {
  const draft = emptyDraft();
  draft.payload.title = from.payload.title;
  draft.meta.categoryId = from.meta.categoryId;
  draft.meta.tagIds = [...from.meta.tagIds];
  draft.meta.primaryAuthorId = from.meta.primaryAuthorId;
  draft.meta.reviewerId = from.meta.reviewerId;
  draft.meta.featuredMediaId = from.meta.featuredMediaId;
  draft.meta.flags = { ...from.meta.flags };
  return draft;
}
