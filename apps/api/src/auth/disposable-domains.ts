/** True when the email domain, or a parent of it, is blocked (bundled list or `extra`). */
export function isBlockedEmailDomain(email: string, extra: readonly string[] = []): boolean {
  const at = email.lastIndexOf("@");
  if (at < 0) return false;
  const labels = email
    .slice(at + 1)
    .toLowerCase()
    .split(".");
  for (let i = 0; i < labels.length - 1; i += 1) {
    const candidate = labels.slice(i).join(".");
    if (DISPOSABLE_EMAIL_DOMAINS.has(candidate) || extra.includes(candidate)) return true;
  }
  return false;
}
